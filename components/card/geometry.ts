/**
 * 카드 한 칸의 기하 — **LinkCard 와 QuickAddCard 가 같은 값을 써야 격자가 흔들리지 않는다.**
 *
 * 원래는 두 파일이 각자 `min-h-[104px] … min-h-[126px]` 을 적어 두고 "C2 의 값"이라는 주석으로만
 * 묶여 있었다. 높이를 고정으로 바꾸면서 한곳으로 올린다 — 값이 둘로 갈라지면 타일만 격자에서
 * 튀는데, 그 어긋남은 눈으로만 보이고 테스트로는 잡히지 않는다.
 *
 * ## 왜 min-height 가 아니라 **고정 높이**인가
 *
 * `min-height` 는 하한일 뿐이라 카드의 실제 높이를 **내용이** 정했다. 제목이 두 줄인 카드가 한 줄인
 * 카드보다 커지고, 격자는 행마다 가장 큰 카드에 맞춰 늘어나므로 **행마다 높이가 달라진다**
 * (사용자 지적 — "높이가 들쭉날쭉하면 안 된다"). 높이를 못 박으면 모든 카드가 같은 크기가 된다.
 *
 * ## 고정값의 근거 — 최악의 카드가 들어가는 높이
 *
 * 세로로 쌓이는 것: 패딩 위아래 + 파비콘 줄(32) + gap 6 + [제목 2줄 + 4 + 설명 3줄] + gap 6 +
 * 하단 줄 mt 5 + 하단 줄(≈17).
 *
 * - ≥820px: 24 + 32 + 6 + (35.1 + 4 + 50.4) + 6 + 5 + 17 ≈ 179.5 → **180px**
 * - <820px: 20 + 32 + 6 + (33.8 + 4 + 50.4) + 6 + 5 + 17 ≈ 174.2 → **176px**
 *
 * 제목 2줄(`max-h-[2.6em]`)·설명 3줄(`max-h-[4.2em]`)이 이 계산의 전제다. 둘 중 하나라도 늘리면
 * 이 값을 다시 계산해라 — 안 그러면 `overflow-hidden` 이 마지막 줄을 잘라 낸다.
 *
 * 본문은 `mt-auto` 로 아래에 붙으므로, 내용이 짧은 카드는 파비콘 아래에 여백이 남는다. 그것이
 * 의도다 — 모든 카드에서 제목·주소·클릭 수의 **세로 위치가 같아진다**.
 */
export const CARD_HEIGHT = 'h-[176px] min-[820px]:h-[180px]';

/**
 * 위 고정 높이의 '하한' 판. **펼쳐진 폼**만 쓴다 — '+ 링크 추가' 폼은 입력 넷 + 버튼 줄이라
 * 카드 한 장보다 키가 크다(≈192px). 고정으로 두면 마지막 줄이 잘려 취소 버튼을 누를 수 없다.
 *
 * 그 한 칸이 커지면 같은 행의 카드도 함께 늘어나지만, 폼을 닫는 순간 되돌아오는 일시적인
 * 상태라 감수한다(편집 중인 격자 한 행 vs. 누를 수 없는 버튼).
 */
